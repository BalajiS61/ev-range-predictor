"""Copy the key result plots from results/ into docs/images/ for the README and report.

results/ is git-ignored (it is regenerated by the step scripts); docs/images/ is
committed so the figures show on GitHub.
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
IMAGES = ROOT / "docs" / "images"

FIGURES = {
    "step2_speed_traces.png": "Step 2 - drive cycles",
    "step3_motor_efficiency_map.png": "Step 3 - motor efficiency map",
    "step3_loss_breakdown.png": "Step 3 - energy breakdown",
    "step3_range_tests.png": "Step 3 - full-depletion range tests",
    "step4_range_vs_temperature.png": "Step 4 - range vs temperature",
    "step4_range_vs_speed.png": "Step 4 - range vs speed",
    "step4_payload_hills_ageing.png": "Step 4 - payload, hills, ageing",
    "step4_scenarios.png": "Step 4 - real-world scenarios",
    "step5_parity_best_model.png": "Step 5 - ML parity plot",
    "step5_model_comparison.png": "Step 5 - model comparison",
    "step5_feature_importance.png": "Step 5 - feature importance",
}


def main() -> None:
    IMAGES.mkdir(parents=True, exist_ok=True)
    missing = []
    for name, label in FIGURES.items():
        src = RESULTS / name
        if src.exists():
            shutil.copy2(src, IMAGES / name)
            print(f"  copied   {name:<34} ({label})")
        else:
            missing.append(name)
            print(f"  MISSING  {name:<34} ({label})")
    if missing:
        print("\nRe-run the step scripts that create the missing plots, then run this again:")
        print("  python scripts/step2_cycles.py | step3_powertrain.py | step4_sensitivity.py | step5_ml.py --reuse")
    else:
        print(f"\nAll {len(FIGURES)} figures copied to {IMAGES}")


if __name__ == "__main__":
    main()
